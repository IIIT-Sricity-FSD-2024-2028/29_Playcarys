import * as fs from 'fs';
import * as path from 'path';

let loadedData: any = {};
try {
  // Same resolution as persistence.ts. These two used to disagree: the WRITER
  // honoured DB_FILE while the READER was hardcoded to the real file, so
  // pointing DB_FILE at a copy isolated writes but silently kept reading
  // production data. That is a bad way to run a test against a scratch
  // database — the isolation looks total and is half there.
  const dbPath =
    process.env.DB_FILE ||
    path.join(__dirname, '..', '..', '..', 'front-end', 'live_database.json');
  if (fs.existsSync(dbPath)) {
    // A UTF-8 BOM makes JSON.parse throw outright, and the catch below turns
    // that into a silent fall back to seed data — which looks like the database
    // mysteriously emptying. Windows editors and PowerShell's Set-Content both
    // write one by default, so strip it rather than lose the file to it.
    const raw = fs.readFileSync(dbPath, 'utf8').replace(/^﻿/, '');
    loadedData = JSON.parse(raw);
  }
} catch (e) {
  console.error('Failed to load live_database.json', e);
}

