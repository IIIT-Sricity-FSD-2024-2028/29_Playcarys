export interface Notification {
  id: number;
  toRole: string | null;
  toUser: number | null;
  from: string;
  avatar: string;
  fromRole: string;
  fromUserId: number;
  msg: string;
  time: string;
  read: boolean;
  // Only meaningful on a broadcast (toRole set, toUser null). That is ONE row read
  // by every user in the role, so `read` on it is shared: the first moderator to
  // mark an announcement read cleared it for all the others. readBy records who has
  // read the shared row; direct rows keep using `read`.
  readBy?: number[];
  replies: any[];

  // ── Fields the frontend has always written, never declared here ──────────
  //
  // These round-trip through db-import and live in live_database.json today,
  // but were absent from this interface, so server-side code could not read or
  // write them without a cast. That is not cosmetic: NotificationService.create()
  // silently dropped `type` for exactly this reason, and a friend request made
  // through the REST API arrived untyped — which is the very field the drawer
  // keys off to draw its Accept / Reject buttons, so the recipient got a
  // message they could not act on.

  /**
   * What KIND of notification this is. Drives the icon, the category filter and,
   * for 'friend_request' and 'invite', the action buttons.
   * In use today: 'friend_request', 'invite', 'system'. notifications.html also
   * styles 'tournament', 'reward', 'warning', 'ban', 'report', 'escalation'.
   * Absent means a plain message.
   */
  type?: string;

  /**
   * Dismissed from the recipient's list. `cleared` is the direct-row flag;
   * `clearedBy` is the per-user list on a SHARED broadcast row, for the same
   * reason `readBy` exists — one user clearing an announcement must not clear
   * it for everyone else in the role.
   */
  cleared?: boolean;
  clearedBy?: (number | string)[];

  /** Set on notifications raised about a specific match. */
  sessionId?: number | string | null;

  /** Chosen category on a message to staff ("Bug Report", "General Inquiry"). */
  subject?: string;
}

