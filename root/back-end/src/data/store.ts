/**
 * A MATCH — one play of a game, by one or more players.
 *
 * Replaces GameSession, which modelled a ROOM: it had a host, a name, a seat
 * count and a live member list, and it existed before anyone played. That shape
 * came from chess, the one first-party game the platform ran itself, and was
 * then applied to every game whether or not it made sense. It did not:
 *
 *   - A single-player game has no lobby and no second party, so a player who
 *     just played Hill Climbing alone was told "session ended" about machinery
 *     that had nothing to do with what they did.
 *   - A real multiplayer game brings its own matchmaking, so a platform room in
 *     front of it was a lobby the player crossed to reach the actual lobby.
 *
 * What survives is the part that was always genuinely needed: the record that a
 * play happened, so match history and achievements have something to hang off.
 *
 * Deliberately ABSENT: name, host, hostId, maxPlayers, and any member list.
 * Who took part is in `match_results` — one row per player per match, which is
 * the correct place for it and already the source getPlayerMatchHistory reads.
 *
 * `status` has no 'waiting': waiting is something a room does, not a match. A
 * match is either being played or finished.
 */
export interface Match {
  /**
   * String, not number. Session ids in the existing data are a mix of small
   * seeded integers and large client-generated ones, some stored as numbers and
   * some as strings, and every comparison in the codebase already coerces with
   * String(). Making that explicit removes a whole class of "the ids look equal
   * but ===  says otherwise" bug rather than carrying it forward.
   */
  match_id: string;
  game_id: number;
  /** Denormalised game name, as sessions carried it — match history renders it. */
  game: string;
  status: 'in-progress' | 'completed';
  mode?: 'casual' | 'ranked';
  start_time: string;
  end_time?: string | null;
  duration: number;
  created_at: string;
  /** Who started this play. Not a "host" — there is no room to host. */
  created_by?: number | null;

  /**
   * Who is playing this match.
   *
   * This is NOT the player_session junction coming back in disguise. That table
   * was a mutable membership list for a LOBBY — people joined it, left it, were
   * kicked from it, and it had to be reconciled against a seat count. This is a
   * fact about one match, written once when play starts and never edited.
   *
   * It exists because presence needs it. `match_results` records who took part,
   * but only once the match is OVER, so during play the only person the
   * platform could name was whoever created the row. In a chess game that is
   * the host alone — the other player would have shown as "Online" while
   * visibly sitting in a game.
   *
   * Single-player matches simply have one entry.
   */
  participants?: number[];
}

