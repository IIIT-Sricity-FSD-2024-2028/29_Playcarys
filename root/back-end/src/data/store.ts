/**
 * Render paise as rupees for display, e.g. 500000 → "₹5,000".
 *
 * Whole rupees only: a prize of "₹5,000.00" reads like a bank statement, and
 * every amount this formats is a headline figure rather than a line item.
 * Uses the en-IN grouping (₹1,00,000, not ₹100,000).
 */
export function formatPaise(paise: number): string {
  return `₹${Math.round((Number(paise) || 0) / 100).toLocaleString('en-IN')}`;
}

