/**
 * One-off migration markers.
 *
 * A store-owned table on purpose. The obvious home was `settings`, but that is
 * a PASSTHROUGH table — persistence.ts holds it separately from the boot
 * snapshot, so a flag written there is never saved. The scrub below would then
 * re-run on every restart and wipe the view counts the platform had since
 * measured honestly, which is a worse bug than the one it fixes.
 */
export interface PlatformFlag {
  flag: string;
  set_at: string;
}
export const platform_flags: PlatformFlag[] = loadedData.platform_flags || [];

/**
 * Retire metrics that were never measured.
 *
 * Three numbers shipped in the seed and were displayed as if the platform had
 * counted them:
 *
 *   views    — nothing anywhere incremented it. Two games carried 10,400 and
 *              8,200, and the publisher dashboard reported them as "Total
 *              Views" with a per-game average. A studio would have drawn real
 *              conclusions about which title to invest in from a number the
 *              platform invented.
 *   rating   — two games carried 4.7 and 4.6. There is no rating endpoint and
 *              no player ever gave a score, so the stars were decoration.
 *   sessions — credited on any awardMatch call, including for games that were
 *              never approved and have no build. Call of Duty sat at 29.
 *
 * Zeroed once, on the first boot after this shipped, and marked so a later
 * restart does not wipe figures the platform has since counted honestly.
 * GET /games/:id/view and the approval gate on royalty are what make these
 * real from here on.
 */
function retireUnmeasuredMetrics(): void {
  if (platform_flags.some((f) => f.flag === 'metrics_retired_v1')) return;

  let cleared = 0;
  for (const g of games as any[]) {
    if (g.views) { g.views = 0; cleared++; }
    if (g.rating) { g.rating = 0; cleared++; }
    // A game that was never approved cannot have been played, so its session
    // count is not a measurement either.
    if (g.game_approval_status !== 'approved' && g.sessions) {
      g.sessions = 0;
      cleared++;
    }
  }
  platform_flags.push({ flag: 'metrics_retired_v1', set_at: new Date().toISOString() });
  if (cleared) {
    console.warn(
      `[store] retired ${cleared} unmeasured metric value(s) — views, ratings ` +
        `and sessions on unapproved games were seed data presented as analytics`,
    );
  }
}

