export interface Game {
  game_id: number;
  game_name: string;
  game_type: string;
  game_status: 'enabled' | 'disabled';
  game_approval_status: 'approved' | 'pending' | 'rejected';
  game_publisher: number;
  desc: string;
  players: string;
  img: string;
  rating: number;
  views: number;
  submittedDate: string;
  sessions: number;

  // ── Delivery: how the game is actually launched ──────────────
  // Without these a Game row is pure metadata and the player-facing
  // "Play" button has nothing to resolve, which is why only the two
  // hardcoded builtin games (chess, hill_climbing) were ever playable.
  //
  //   'hosted'     — Model A: publisher uploaded a .zip, we unpacked it
  //                  to front-end/<play_path> and serve it ourselves.
  //   'selfhosted' — Model B: publisher hosts the build on their own
  //                  CDN; we embed game_url in an iframe.
  hosting_type?: 'hosted' | 'selfhosted';
  /** Model A only. Relative to the frontend web root, e.g. "games/neon-drift-9". */
  play_path?: string;
  /** Model B only. Absolute https:// URL of the publisher's build. */
  game_url?: string;
  /** Model B only. Optional endpoint we POST match events to. */
  webhook_url?: string;

  /**
   * Shared secret for signing traffic between the platform and this publisher.
   *
   * Used both ways: the platform HMAC-signs the match token it hands a player,
   * and the publisher HMAC-signs the result their server posts back. Without a
   * shared secret a tournament result is just an HTTP request anybody could
   * send, and the whole bracket becomes forgeable by a curious player.
   *
   * Generated by the platform at publish time; shown to the publisher once.
   */
  webhook_secret?: string;
  bundle_size?: number;
  bundle_uploaded_at?: string;

  /**
   * Most Carys points one match of this game may award a player.
   *
   * A game declares its own economy by passing carys_earned through the SDK,
   * and nothing used to bound it — a published game could award 999,999 points
   * per match and own the leaderboard outright. The publisher still chooses the
   * numbers; this is the ceiling an admin sees at review time and the server
   * clamps to. Absent means the platform default applies.
   */
  max_carys_per_match?: number;

  // ── What KIND of game this is ────────────────────────────────
  /**
   * Declared by the publisher at publish time: does this game seat one player
   * or several?
   *
   * Until now nothing on the row answered that. `multiplayerMode()` in
   * game-launch.js guessed it from a hardcoded two-entry map plus a regex over
   * the free-text `players` string ("2-64", "1-6"), so every game outside that
   * map was classified by parsing marketing copy. A publisher writing
   * "1 player" vs "Single player" got different behaviour from the platform.
   *
   * This is the field the catalogue, the launcher and the tournament type all
   * read instead. `players` stays as the human-readable blurb it always was.
   */
  game_mode?: 'single' | 'multi';

  /**
   * Whether a third party may watch a match of this game in progress.
   *
   * Spectating used to mean "join the platform room and read its state", which
   * only ever worked for chess and dies with the room concept. A publisher who
   * runs their own netcode is the only party that can actually offer a
   * spectator view, so they declare it here and supply the URL to open.
   *
   * spectate_url_template accepts {match_id} and {player_id} placeholders.
   */
  supports_spectate?: boolean;
  spectate_url_template?: string;

  /**
   * Lifetime ceiling on everything this game's achievements may ever pay out,
   * summed across all APPROVED achievements.
   *
   * Per-achievement caps alone are not enough: 500 Carys each is reasonable,
   * 500 Carys times forty achievements is a publisher minting the leaderboard.
   * Achievements are one-time per player, so this is a genuine one-off budget
   * rather than a rate — checked when an achievement is created and again when
   * an admin approves it. An admin may raise a specific game's budget at
   * review time. Absent means the platform default applies.
   */
  achievement_budget_carys?: number;
  achievement_budget_xp?: number;

  // ── Review: what an admin actually approved ──────────────────
  // game_approval_status says whether a LISTING is approved. These say
  // which BUILD was approved, which is a different question — without
  // them a publisher can pass review with a clean bundle and then
  // re-upload anything they like while the listing stays live.
  //
  // All of these are server-owned: they are written by the scan and by
  // the approve endpoint, never by the client, and app.controller.ts
  // carries them forward across a db-import for that reason.
  /** Static-scan result for the currently installed build. */
  scan?: ScanReport;
  /** Fingerprint of the currently installed build (mirrors scan.bundle_hash). */
  bundle_hash?: string;
  /** Fingerprint of the build an admin signed off on. Drift means re-review. */
  approved_bundle_hash?: string;
  /** For self-hosted games: the game_url as it read at approval time. */
  approved_game_url?: string;
  approved_by?: number;
  approved_at?: string;
  /** Why the listing was last approved or rejected, shown to the publisher. */
  review_note?: string;
  /** Set when a previously approved game was pulled back for re-review. */
  review_required_reason?: string;
}

/**
 * One immutable review decision. Games carry only their CURRENT state;
 * this is the history — who approved which exact build, and when.
 * Append-only, like match_results.
 */
export interface GameReview {
  review_id: number;
  game_id: number;
  /** user_id of the admin who decided. */
  reviewer_id: number;
  reviewer_name: string;
  decision: 'approved' | 'rejected';
  /** The build this decision applies to. Null for self-hosted games. */
  bundle_hash?: string;
  game_url?: string;
  scan_verdict?: ScanVerdict;
  /** Counts at decision time, so history stays readable after a re-scan. */
  scan_summary?: Record<string, number>;
  note: string;
  /** True when a fail-verdict build was approved anyway (superuser only). */
  override: boolean;
  decided_at: string;
}

/**
 * A publisher-defined achievement for one game.
 *
 * Declared at publish time rather than invented at runtime, on purpose: an
 * admin reviews the list alongside the build, and the unlock endpoint only
 * accepts codes that appear here. That makes achievements a strictly tighter
 * contract than match results — a game cannot mint a reward it never declared.
 */
export interface Achievement {
  achievement_id: number;
  /**
   * The game this belongs to, or null for a PLATFORM achievement.
   *
   * Platform achievements ("play your first match", "make 5 friends") are
   * defined by an admin, belong to no game, are exempt from any publisher's
   * budget, and are evaluated by the platform from its own data rather than
   * reported by a game — a game has no way to know how many friends a player
   * has, and should not be trusted with it if it did.
   */
  game_id: number | null;
  /** Slug the game unlocks by, e.g. "first_win". Unique within a game. */
  code: string;
  name: string;
  description: string;
  /** Single emoji shown on the card. */
  icon: string;
  /** Carys granted once, the first time a player earns it. */
  carys_reward: number;
  /**
   * XP granted once, alongside the Carys. Separate currency, separate cap:
   * Carys are spendable and XP is progression, so a publisher tuning one
   * should not be forced to move the other.
   */
  xp_reward?: number;
  /** Platform-wide title the player may then display, e.g. "Hill Conqueror". */
  title_awarded?: string;
  /** Hidden from the game's achievement list until it is earned. */
  secret?: boolean;
  created_at: string;

  /**
   * Publisher proposes, admin approves.
   *
   * An achievement pays real Carys, so letting a publisher mint one unreviewed
   * is the same hole `max_carys_per_match` was opened to close. A row sitting
   * at 'pending' is visible to its publisher and to the admin review console
   * and is NOT grantable — the unlock endpoint refuses it.
   *
   * Absent means 'approved': the five achievements seeded before this field
   * existed were created through the real endpoint under admin control, so
   * treating a missing status as approved keeps them working rather than
   * silently switching them off.
   */
  status?: 'pending' | 'approved' | 'rejected';
  approved_by?: number;
  approved_at?: string;
  /** Why an admin rejected it, shown back to the publisher. */
  review_note?: string;

  /**
   * PLATFORM achievements only (game_id === null).
   *
   * What the platform measures, and how much of it is needed. A game reports
   * its own achievements by code; these are the ones no game could report
   * honestly — "play your first match" spans every game, and "make 5 friends"
   * is not something a game can see at all.
   *
   *   first_match       played at least one match anywhere
   *   matches_played    threshold matches across the platform
   *   friends           threshold accepted friendships
   *   first_tournament  entered at least one tournament
   */
  rule?: string;
  threshold?: number;
}

/**
 * One player earning one achievement. Append-only and unique on
 * (user_id, achievement_id) — earning something is a historical fact, and the
 * uniqueness is what stops a game from re-unlocking the same reward in a loop.
 */
export interface PlayerAchievement {
  user_id: number;
  achievement_id: number;
  /** Null when this is a platform achievement rather than a game's. */
  game_id: number | null;
  unlocked_at: string;
  /**
   * The match this was earned in, when a game reported it.
   *
   * Named session_id for the rows already written under that name; a single-
   * player play is a MATCH, not a session, and Phase 1 renames the table it
   * points at. Kept as a string because match ids are strings there.
   */
  session_id?: string;
  /** Carys actually granted, after the cap. Recorded so history stays readable. */
  carys_granted: number;
  /** XP actually granted, after the cap. Same reasoning as carys_granted. */
  xp_granted?: number;
}

export interface Tournament {
  tournament_id: number;
  game_id: number;
  tournament_name: string;
  desc: string;
  participants: number;
  maxParticipants: number;
  status: 'upcoming' | 'in-progress' | 'completed';
  start_date: string;
  end_date: string;
  regClose: string;
  prize: string;
  organizer: number;

  // ── How this tournament is actually decided ──────────────────
  /**
   * 'score'   — everyone plays the same single-player game and the best
   *             number wins. No opponents, no bracket, no rooms. Two of the
   *             five seeded tournaments are already this shape.
   * 'bracket' — knockout rounds between pairs, for a multiplayer game.
   *
   * Absent falls back to the GAME's declared game_mode, so tournaments
   * created before this field existed still behave sensibly.
   */
  format?: 'score' | 'bracket';

  /**
   * SCORE contests only: which number off the match result decides it, and
   * which direction is better.
   *
   * The leaderboard used to be hardcoded to `game_id === '8'` and the field
   * `distance` — so a score contest for any other game ranked everyone at
   * zero. Declaring the metric is what makes the same leaderboard work for a
   * racing game's lap time (lower is better) and a shooter's score.
   */
  metric?: string;                       // e.g. 'distance', 'score', 'time_ms'
  direction?: 'high' | 'low';            // 'low' for lap times
  metric_label?: string;                 // e.g. 'Distance', shown as a column head
  metric_unit?: string;                  // e.g. 'm', 's'

  // ── Multi-game extension ──────────────────────────────────────
  /**
   * 'single' (default, absent means single) — everything above (game_id,
   * format, metric, direction) decides the whole tournament directly, exactly
   * as it always has. 'multi' — this tournament is a SEQUENCE of stages, each
   * its own game with its own format/metric, declared as a TournamentGame row
   * per stage. game_id on a multi tournament is not used to decide anything;
   * it is kept 0 so nothing that reads it by accident silently treats a
   * multi-game tournament as single-game.
   *
   * Deliberately a NEW field with a NEW meaning rather than overloading an
   * existing one — every single-game tournament ever created (seeded or real)
   * has no `type` at all, and `type ?? 'single'` is what keeps them behaving
   * exactly as before this field existed.
   */
  type?: 'single' | 'multi';

  /**
   * 'public' (default) — listed for anyone to browse and register.
   * 'private' — only reachable by invite_code; still shows in the organizer's
   * own list and the registered players' my-tournaments list, but is left out
   * of the public browse listing (see TournamentService.findAll).
   */
  visibility?: 'public' | 'private';

  /** Only meaningful when visibility === 'private'. Share this to let someone register. */
  invite_code?: string;

  /**
   * Who is allowed to organize is unchanged (any signed-in user id — this
   * controller has never had a @Roles restriction, which is what already lets
   * both players and publishers create one). This just records which kind of
   * account actually did, so the UI can show "Community" vs "Official".
   */
  organizer_role?: 'player' | 'publisher' | 'moderator' | 'admin' | 'superuser';

  // ── Kind / Community / Teams extension ────────────────────────
  /**
   * The three kinds shown in the UI. Deliberately derived-not-stored where
   * possible (see TournamentService.enrich's `kind` field) — `kind` here would
   * just duplicate organizer_role + group_id and risk disagreeing with them.
   * OFFICIAL = organizer_role 'publisher'. CASUAL = organizer_role 'player'
   * with no group_id. COMMUNITY = organizer_role 'player' WITH a group_id.
   */

  /**
   * Set only on a Community tournament — which Group it belongs to. The
   * organizer must be that group's owner or an officer (checked in
   * TournamentService.create). A Community tournament is always scoped to
   * exactly one group; it is not a general "tag", so there is no group_ids[].
   */
  group_id?: number;

  team_size?: number;

  // ── Money ─────────────────────────────────────────────────────
  /**
   * Entry fee in paise, 0 for a free tournament.
   *
   * Replaces nothing — there was no entry-fee field at all, yet two seeded
   * transactions record `tournament_entry` payments. Money left a pool that
   * nothing filled. This is the field that makes those rows honest.
   */
  entry_fee_paise?: number;
  /** Entry may be paid in either currency. Carys entries cost the platform nothing. */
  entry_currency?: "INR" | "CARYS";
  entry_fee_carys?: number;
  /** Platform cut of the entries, percent. Subscribers who organise get a reduced rate. */
  rake_pct?: number;
  /**
   * The real pool, in paise. `prize` above stays as the display string, but it
   * is DERIVED from this number from here on — it used to be free text
   * ("$2500") that nothing funded and nothing could pay out.
   */
  prize_pool_paise?: number;
  /** Materialised split of prize_pool_paise, so the shares are data and not a formula in a template. */
  prize_distribution?: TournamentPrizeShare[];
}

export interface TournamentPrizeShare {
  place: string;
  pct: number;
  amount_paise: number;
}

/**
 * One STAGE of a multi-game tournament — one game, with its own format
 * (score or bracket) and its own metric, played as a leg of a larger
 * tournament. A single-game tournament has NO TournamentGame rows at all;
 * everything it needs already lives directly on the Tournament row, exactly
 * as before this type existed. TournamentGame only exists for `type: 'multi'`.
 *
 * This is the one new entity the whole multi-game extension is built on —
 * everything else (registration, chat, disputes, match tokens) is reused
 * unchanged by scoping it with tournament_game_id instead of inventing a
 * parallel registration/chat/dispute system per game.
 */
export interface TournamentGame {
  tournament_game_id: number;
  tournament_id: number;
  game_id: number;
  /** Play order — stage 1, stage 2, ... Stages need not run concurrently. */
  stage_order: number;
  format: 'score' | 'bracket';
  /** SCORE stages only — same meaning as Tournament.metric. */
  metric?: string;
  direction?: 'high' | 'low';
  metric_label?: string;
  metric_unit?: string;
  /**
   * Multiplies the points this stage's placements contribute to the overall
   * standing (see TournamentPlayService.STAGE_POINTS). A weight of 2 on the
   * "Grand Final" stage of a fest makes it worth double an early stage.
   * Defaults to 1 — every stage counts equally unless the organizer says
   * otherwise.
   */
  points_weight: number;
  status: 'pending' | 'active' | 'completed';
}

