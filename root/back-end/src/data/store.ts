// ============================================================
//  MIGRATION: USD floats → INR paise
//
//  The seeded economy was priced in US dollars as floating-point numbers
//  (price: 2.99) and tournament prizes were free text ("$5000"). This
//  converts both, in place, at boot.
//
//  Idempotent by construction: every branch checks for the NEW field and
//  skips a row that already has it, so restarting the server does not
//  re-convert — which would otherwise multiply every price by 100 on every
//  boot until the numbers became nonsense.
// ============================================================

/**
 * Rupee price by rarity band, in paise.
 *
 * Deliberately NOT a straight FX conversion of the old dollar prices. $2.99 at
 * any plausible rate lands on ₹254 — an amount no Indian storefront would ever
 * print. Rarity was already what the seed priced on, so the bands are priced
 * directly at the points this market actually uses.
 */
const PRICE_PAISE_BY_RARITY: Record<string, number> = {
  common: 7_900,      // ₹79
  rare: 14_900,       // ₹149
  epic: 29_900,       // ₹299
  legendary: 49_900,  // ₹499
};

/**
 * Carys price by rarity band — roughly one to five hours of play.
 *
 * Set against the value of an hour (~600 Carys) rather than against the rupee
 * price, so cash stays the fast path and play the free one: ₹79 buys what
 * about 50 minutes of playing buys.
 */
const CARYS_PRICE_BY_RARITY: Record<string, number> = {
  common: 500,
  rare: 1_000,
  epic: 2_000,
  legendary: 3_000,
};

/** Rupee price by plan, in paise. Same reasoning as the rarity bands. */
const PRICE_PAISE_BY_PLAN: Record<string, number> = {
  pro: 39_900,       // ₹399
  pro_plus: 79_900,  // ₹799
};

/** Monthly Carys stipend by plan. */
const STIPEND_BY_PLAN: Record<string, number> = {
  pro: 500,
  pro_plus: 1_500,
};

/** Rupees per US dollar. Used only for rows with no band to price against. */
const SEED_USD_TO_INR = 85;

function usdFloatToPaise(usd: number): number {
  // Round to whole rupees first, then express in paise.
  return Math.round(usd * SEED_USD_TO_INR) * 100;
}

function migrateEconomyToInr(): void {
  for (const item of cosmetic_items as any[]) {
    if (item.price_paise === undefined) {
      item.price_paise =
        PRICE_PAISE_BY_RARITY[String(item.rarity)] ??
        usdFloatToPaise(Number(item.price) || 0);
      delete item.price;
    }
    if (item.price_carys === undefined) {
      item.price_carys = CARYS_PRICE_BY_RARITY[String(item.rarity)] ?? 1_000;
    }
  }

  for (const plan of subscription_plans as any[]) {
    if (plan.price_paise === undefined) {
      plan.price_paise =
        PRICE_PAISE_BY_PLAN[String(plan.id)] ??
        usdFloatToPaise(Number(plan.price) || 0);
      delete plan.price;
    }
    if (plan.stipend_carys === undefined) {
      plan.stipend_carys = STIPEND_BY_PLAN[String(plan.id)] ?? 0;
    }

    // ── Only advertise what the code delivers ──────────────────
    //
    // The seeded lists promised five benefits per tier and the platform
    // honoured one. "Unlimited Quick Play" and "All tournaments" describe
    // limits that do not exist, so they were free already. "No ads" — there are
    // no ads. "Priority matchmaking", "Early access games", "Animated avatars",
    // "Downloadable reports" and "Season tracking" are not built.
    //
    // Charging ₹399 a month for a list that is four-fifths fiction is the one
    // thing a paid tier must never do, so the list is rewritten from what is
    // actually enforced rather than the copy the seed shipped with. Add a line
    // back here when the feature behind it exists — not before.
    const stipend = `${plan.stipend_carys.toLocaleString('en-IN')} Carys every month`;
    const rake = plan.id === 'pro_plus' ? '3%' : '6%';
    plan.features = [
      stipend,                                    // EconomyService.claimStipend
      `Only ${rake} platform cut on tournaments you run`, // rakePctFor()
      'Create private, invite-only tournaments',   // canCreatePrivateTournament()
    ];
    if (plan.id === 'pro_plus') {
      plan.features.unshift('Everything in Pro');
    }
  }

  for (const sub of subscriptions as any[]) {
    if (sub.price_paise === undefined) {
      // Price what the subscriber's tier now costs, so an existing subscription
      // does not sit at a rupee figure the plan no longer offers.
      sub.price_paise =
        PRICE_PAISE_BY_PLAN[String(sub.tier)] ??
        usdFloatToPaise(Number(sub.price) || 0);
      delete sub.price;
    }
    if (sub.last_stipend_at === undefined) sub.last_stipend_at = null;
  }

  for (const tx of transactions as any[]) {
    if (tx.amount_paise === undefined) {
      tx.amount_paise = usdFloatToPaise(Number(tx.amount) || 0);
      delete tx.amount;
    }
    if (tx.currency === undefined) tx.currency = 'INR';
  }

  for (const t of tournaments as any[]) {
    if (t.entry_fee_paise === undefined) {
      // Everything seeded predates entry fees, so it was free to enter.
      t.entry_fee_paise = 0;
    }
    if (t.rake_pct === undefined) t.rake_pct = DEFAULT_RAKE_PCT;
    if (t.prize_pool_paise === undefined) {
      // Carry the stated prize across as a sponsored pool. It was a string
      // that nothing funded; at least now it is a number that pays out.
      const stated = parseInt(String(t.prize ?? '').replace(/[^0-9]/g, ''), 10) || 0;
      t.prize_pool_paise = stated * 100;
      // Re-render the display string in rupees. `prize` is derived from the
      // pool from here on, never the other way round.
      t.prize = formatPaise(t.prize_pool_paise);
    }
  }

  for (const p of publisher_profiles as any[]) {
    if (p.revenue_pcp === undefined) p.revenue_pcp = 0;
    if (p.balance_paise === undefined) p.balance_paise = 0;
    if (p.lifetime_earned_paise === undefined) p.lifetime_earned_paise = 0;
    // Everything earned before payouts existed is treated as already settled,
    // so switching this on does not retroactively owe two studios ₹4,500.
    if (p.settled_pcp === undefined) p.settled_pcp = p.revenue_pcp || 0;
    if (p.settled_rake_paise === undefined) p.settled_rake_paise = 0;
  }
}

