// Everyone owns the default body AND the default outfit, and wears both unless
// they buy something else.
//
// The outfit matters as much as the body: without it the 3D figure renders as a
// bare grey mannequin, which reads as broken rather than as "no cosmetics yet".
// Both are free and permanent, so this is a floor rather than a grant.
/** The free floor every player gets: base body + trainee outfit. */
export const DEFAULT_KIT = [101, 110];

for (const p of player_profiles) {
  for (const itemId of DEFAULT_KIT) {
    if (user_cosmetics.some((u) => u.user_id === p.user_id && u.item_id === itemId)) continue;

    // Equipped only when nothing else already occupies that slot — a player who
    // bought the Champion Plate should not be put back in the trainee kit by a
    // restart.
    const slot = cosmetic_items.find((c) => c.id === itemId)?.slot;
    const slotTaken = user_cosmetics.some((u) => {
      if (u.user_id !== p.user_id || !u.is_equipped) return false;
      return cosmetic_items.find((c) => c.id === u.item_id)?.slot === slot;
    });

    user_cosmetics.push({
      user_id: p.user_id,
      item_id: itemId,
      purchased_at: new Date(0).toISOString().slice(0, 10),
      is_equipped: !slotTaken,
    });
  }
}


/**
 * Give a brand-new player the free defaults.
 *
 * The boot loop above only covers profiles that exist when the process starts,
 * so anyone who signs up afterwards would get a bare grey mannequin — the exact
 * thing the default kit exists to prevent. Exported so the two places that
 * create a profile (auth registration and the users service) can call it.
 *
 * Idempotent: an id the player already owns is skipped.
 */
export function grantDefaultKit(userId: number): void {
  for (const itemId of DEFAULT_KIT) {
    if (user_cosmetics.some((u) => u.user_id === userId && u.item_id === itemId)) continue;
    user_cosmetics.push({
      user_id: userId,
      item_id: itemId,
      purchased_at: new Date().toISOString(),
      is_equipped: true,
    });
  }
}
