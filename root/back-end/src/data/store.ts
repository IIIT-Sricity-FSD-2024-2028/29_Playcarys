// ============================================================
//  ECONOMY
//
//  Six of these tables have sat in live_database.json since the seed was
//  written with ZERO lines of code reading or writing them — 30 cosmetics
//  nobody could buy, 2 subscription plans nobody could subscribe to, 16
//  transactions recording money that never moved. They survived on disk only
//  because db-import passes unknown keys straight through to the file.
//
//  They are declared here so the backend owns them. Two currencies:
//
//    Carys — earned by playing. The soft currency. Server-authoritative:
//            carys_ledger is the record and player_profiles.carys_points is
//            a cached total that must always equal the ledger's last
//            balance_after for that user.
//
//    INR   — the money side, stored ONLY as integer paise. Never floats:
//            4.99 has no exact binary representation, and a rounding error
//            in a balance is a bug you cannot apologise your way out of.
//            There is no payment gateway here, so every INR flow is
//            simulated — the states are real, the money is not.
// ============================================================

