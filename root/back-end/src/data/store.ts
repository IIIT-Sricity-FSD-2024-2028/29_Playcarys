// ── Tables the sync used to drop on the floor ────────────────────────────────
//
// These existed on the frontend but were never registered here, so they were
// absent from /db-export. Every page load overwrote localStorage with that
// export, which meant the data was destroyed on the next refresh:
//
//   tournament_matches  → the generated BRACKET. The publisher pressed "Start
//                         Tournament", the bracket appeared, and one reload later
//                         every player saw "Bracket not generated yet." Verified:
//                         3 matches created, 0 present after a refresh.
//   tournament_results  → final standings/payouts, lost the same way.
//   deleted_tournaments → the tombstone list, so deleted tournaments came back.
//   favorites / reviews → the ♥ on the games page and player ratings.
//
// tournament_matches and tournament_results were typed `any[]` here because the
// frontend owned their shape and this store was a pass-through mirror of it.
// That is exactly the problem: bracket generation, advancement and standings run
// in db.js, on the client, so a player can forge a win by editing their own copy
// and syncing. Typing them is the first step of moving that logic server-side.

/**
 * One match in a generated bracket.
 *
 * Shape mirrors what DB.startTournament() in db.js writes today, so existing
 * rows validate against it unchanged.
 */
export interface TournamentMatch {
  /** Composite and human-readable, e.g. "T3R1M0" = tournament 3, round 1, match 0. */
  match_id: string;
  /** camelCase because the client writes it that way; renaming it orphans live rows. */
  tournamentId: number | string;
  round: number;
  /** A player id, the literal "BYE", or null for a slot not yet fed by a parent match. */
  player1: number | string | null;
  player2: number | string | null;
  score1: number;
  score2: number;
  /** 'pending' means a result was reported and is awaiting the opponent's confirmation. */
  status: 'waiting' | 'pending' | 'completed' | 'disputed';
  winnerId: number | string | null;
  /** The match the winner feeds into. Null on the final. */
  parentMatchId: string | null;
  /** Dual-report fallback for games with no result webhook. */
  reportedWinner?: number | string | null;
  reportedBy?: number | string | null;
  /**
   * Which stage this match belongs to, for a multi-game tournament. Absent on
   * every single-game tournament's matches — they need no stage, there is
   * only ever the one game — so every existing row and every piece of code
   * that filters matches by tournamentId alone keeps working unchanged.
   */
  tournament_game_id?: number;
}

/**
 * Final standings for a completed tournament.
 *
 * Empty in every database on disk and written by nothing today — the type is
 * declared so Phase 6 has one definition to build against rather than inventing
 * a second shape next to the first.
 */
export interface TournamentResult {
  tournament_id: number | string;
  player_id: number;
  placement: number;
  /** The ranked metric for a score contest (distance, points); wins for a bracket. */
  score?: number;
  prize_awarded?: string;
  recorded_at: string;
}

