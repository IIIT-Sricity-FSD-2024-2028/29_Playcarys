/**
 * GAME SAVES — physical storage the platform provides, one blob per player per
 * game.
 *
 * The platform provides the storage; the GAME owns what goes in it and what it
 * means. Hill Climbing's coins and diamonds live in a per-browser localStorage
 * key today (`hillclimb_wallet_<userId>`), so a player's progress is stranded on
 * whichever laptop earned it — which is not how the same game behaves on a
 * phone, where the OS gives it durable per-user storage.
 *
 * `data` is an opaque JSON string on purpose: the platform must not care about
 * its contents, and storing it as a string is what makes the size cap below
 * measurable and enforceable.
 *
 * Last-write-wins, NOT append-only: a save is current state, not a historical
 * fact, and the newest one is the only one that matters. Primary key is
 * (user_id, game_id) — one blob each, and game A can never address game B's.
 */
export interface GameSave {
  user_id: number;
  game_id: number;
  /** Opaque to the platform. JSON string, never parsed here. */
  data: string;
  updated_at: string;
  /** Byte length of `data`, stored so a quota check needs no re-measure. */
  bytes: number;
}
export const game_saves: GameSave[] = loadedData.game_saves || [];

/**
 * Hard ceiling on one (player, game) save blob.
 *
 * Uploaded games are third-party code writing into our only data file, which is
 * loaded whole into memory at boot and rewritten whole on every change. Without
 * a bound, one careless autosave loop fills the disk and takes the platform
 * down for everyone — the same class of problem `max_carys_per_match` exists to
 * bound. 64 KB is far more than a coin count needs and far less than can hurt.
 */
export const MAX_GAME_SAVE_BYTES = 64 * 1024;

